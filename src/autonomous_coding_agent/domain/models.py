"""Validated domain models for the Autonomous Coding Agent."""

from enum import StrEnum
from pathlib import Path, PurePosixPath, PureWindowsPath
from typing import Self
from uuid import uuid4

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


class DomainModel(BaseModel):
    """Base class for domain models."""

    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
        validate_assignment=True,
    )


def _normalize_relative_path(value: str) -> str:
    """Validate and normalize a repository-relative path.

    This is lexical validation only. Filesystem operations must
    additionally enforce workspace containment and symlink safety.
    """
    normalized = value.strip().replace("\\", "/")
    posix_path = PurePosixPath(normalized)
    windows_path = PureWindowsPath(value)

    if (
        not normalized
        or "\x00" in normalized
        or posix_path.is_absolute()
        or windows_path.is_absolute()
        or windows_path.drive
        or ".." in posix_path.parts
    ):
        raise ValueError("Path must be a safe repository-relative path.")

    result = posix_path.as_posix()

    if result in ("", "."):
        raise ValueError("Path must identify a file.")

    return result


class TaskStatus(StrEnum):
    """Possible lifecycle states of an agent task."""

    PENDING = "pending"
    RUNNING = "running"
    AWAITING_APPROVAL = "awaiting_approval"
    SUCCEEDED = "succeeded"
    FAILED = "failed"
    REJECTED = "rejected"
    CANCELLED = "cancelled"


class ApprovalStatus(StrEnum):
    """Possible human approval decisions."""

    PENDING = "pending"
    APPROVED = "approved"
    REJECTED = "rejected"


class FileChangeType(StrEnum):
    """Types of repository file changes."""

    ADDED = "added"
    MODIFIED = "modified"
    DELETED = "deleted"
    RENAMED = "renamed"


class TaskRequest(DomainModel):
    """A coding task submitted by a user."""

    task_id: str = Field(
        default_factory=lambda: str(uuid4()),
        min_length=1,
        max_length=64,
    )
    task_description: str = Field(min_length=1, max_length=10_000)
    repository_path: Path

    @field_validator("repository_path")
    @classmethod
    def require_absolute_repository_path(cls, value: Path) -> Path:
        """Require an unambiguous local repository path."""
        if not value.is_absolute():
            raise ValueError("Repository path must be absolute.")
        return value


class PlanStep(DomainModel):
    """An individual step in an execution plan."""

    step_number: int = Field(ge=1)
    description: str = Field(min_length=1, max_length=2_000)
    target_files: list[str] = Field(default_factory=list, max_length=100)

    @field_validator("target_files")
    @classmethod
    def validate_target_files(cls, values: list[str]) -> list[str]:
        """Restrict target files to repository-relative paths."""
        return [_normalize_relative_path(value) for value in values]


class ExecutionPlan(DomainModel):
    """Structured execution plan generated by the planning agent."""

    goal: str = Field(min_length=1, max_length=2_000)
    steps: list[PlanStep] = Field(min_length=1, max_length=50)
    acceptance_criteria: list[str] = Field(min_length=1, max_length=100)

    @model_validator(mode="after")
    def validate_unique_step_numbers(self) -> Self:
        """Ensure every execution step has a unique number."""
        numbers = [step.step_number for step in self.steps]

        if len(numbers) != len(set(numbers)):
            raise ValueError("Execution plan contains duplicate step numbers.")

        return self


class RepositorySnapshot(DomainModel):
    """A lightweight description of an inspected repository."""

    repository_path: Path
    base_commit: str | None = None
    files: list[str] = Field(default_factory=list, max_length=10_000)
    languages: list[str] = Field(default_factory=list)
    dependency_files: list[str] = Field(default_factory=list)

    @field_validator("repository_path")
    @classmethod
    def require_absolute_repository_path(cls, value: Path) -> Path:
        """Require an absolute repository path."""
        if not value.is_absolute():
            raise ValueError("Repository path must be absolute.")
        return value

    @field_validator("files", "dependency_files")
    @classmethod
    def validate_repository_files(cls, values: list[str]) -> list[str]:
        """Validate repository-relative file paths."""
        return [_normalize_relative_path(value) for value in values]

    @property
    def file_count(self) -> int:
        """Return the number of inspected files."""
        return len(self.files)


class FileChange(DomainModel):
    """A proposed modification to a repository file."""

    path: str
    change_type: FileChangeType
    diff: str = Field(min_length=1)
    previous_path: str | None = None

    @field_validator("path", "previous_path")
    @classmethod
    def validate_file_paths(cls, value: str | None) -> str | None:
        """Reject absolute paths and directory traversal."""
        if value is None:
            return None
        return _normalize_relative_path(value)

    @model_validator(mode="after")
    def validate_rename(self) -> Self:
        """Require the original path when a file is renamed."""
        if self.change_type == FileChangeType.RENAMED:
            if self.previous_path is None:
                raise ValueError("Renamed files require a previous_path.")
        elif self.previous_path is not None:
            raise ValueError("previous_path is only valid for renamed files.")

        return self


class ExecutionResult(DomainModel):
    """Result returned by a sandbox execution."""

    command: list[str] = Field(min_length=1, max_length=64)
    exit_code: int | None = None
    stdout: str = ""
    stderr: str = ""
    duration_seconds: float = Field(ge=0)
    timed_out: bool = False

    @field_validator("command")
    @classmethod
    def validate_command(cls, values: list[str]) -> list[str]:
        """Reject empty command arguments."""
        if any(not value.strip() for value in values):
            raise ValueError("Command arguments cannot be empty.")
        return values

    @property
    def succeeded(self) -> bool:
        """Return whether execution completed successfully."""
        return self.exit_code == 0 and not self.timed_out


